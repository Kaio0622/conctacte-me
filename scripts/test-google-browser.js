const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

module.exports = async ({ base }) => {
  const { chromium } = require('playwright');
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const capturas = fs.mkdtempSync(path.join(os.tmpdir(), 'contactme-google-ui-'));
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    await context.route('https://**', route => route.abort());
    const page = await context.newPage();
    const erros = [];
    page.on('pageerror', e => erros.push(e.message));
    await page.goto(base + '/#/entrar');
    await page.waitForFunction(() => !document.getElementById('entrarGoogle')?.disabled);
    assert.equal(await page.locator('#lSenha').count(), 1, 'login com senha permanece');
    await page.locator('#temaSeletor').selectOption('claro');
    await page.screenshot({ path: path.join(capturas, 'google-claro.png'), fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#temaSeletor').selectOption('escuro');
    await page.screenshot({ path: path.join(capturas, 'google-escuro-celular.png'), fullPage: true, animations: 'disabled' });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'sem rolagem horizontal no celular');
    let iniciou = false;
    await page.route('**/api/auth/google/iniciar', route => {
      iniciou = true;
      return route.fulfill({ contentType: 'text/html', body: '<p>Destino OAuth de teste</p>' });
    });
    await page.locator('#entrarGoogle').click();
    await page.waitForURL('**/api/auth/google/iniciar');
    assert.ok(iniciou, 'botão inicia o fluxo OAuth');
    await page.goto(base + '/#/cadastro');
    assert.equal(await page.locator('#entrarGoogle').count(), 1);
    assert.equal(await page.locator('#cSenha').count(), 1);
    await page.route('**/api/auth/google/resultado', route => route.fulfill({ json: { cadastroGoogle: { nome: 'Pessoa Google', email: 'pessoa@teste.local' } } }));
    await page.goto(base + '/#/google');
    await page.locator('#cEmail').waitFor();
    assert.equal(await page.locator('#cEmail').inputValue(), 'pessoa@teste.local');
    assert.ok(await page.locator('#cEmail').evaluate(el => el.readOnly));
    assert.equal(await page.locator('#cSenha').count(), 0, 'cadastro Google não exige criar senha');
    await page.locator('[data-tipo="prestador"]').click();
    await page.locator('#cCategoria option[value="eletrica"]').waitFor({ state: 'attached' });
    assert.equal(await page.locator('#cEmail').inputValue(), 'pessoa@teste.local');
    assert.equal(await page.locator('#cSenha').count(), 0);
    await page.locator('[data-tipo="cliente"]').click();
    let enviado;
    await page.route('**/api/auth/cadastro/cliente', route => {
      enviado = route.request().postDataJSON();
      return route.fulfill({ json: { token: 'sessao-teste', usuario: { id: 'ui', nome: 'Pessoa Google', papel: 'cliente' } } });
    });
    await page.locator('#cTelefone').fill('11999999999');
    await page.locator('#cCidade').fill('São Paulo');
    await page.locator('#formCadastro button[type="submit"]').click();
    await page.waitForURL('**/#/busca');
    assert.equal(enviado.googleCadastro, true);
    assert.equal(enviado.senha, undefined);
    await page.evaluate(() => localStorage.removeItem('contactme.sessao'));
    await page.unroute('**/api/auth/google/resultado');
    await page.route('**/api/auth/google/resultado', route => route.fulfill({ json: { vincular: true, email: 'existente@teste.local' } }));
    await page.goto(base + '/#/google');
    await page.locator('#senhaVincular').waitFor();
    await page.route('**/api/auth/google/vincular', route => route.fulfill({ status: 400, json: { erro: 'Senha incorreta de teste' } }));
    await page.locator('#senhaVincular').fill('senha-errada');
    await page.locator('#formVincularGoogle button').click();
    await page.getByText('Senha incorreta de teste').waitFor();
    assert.equal(await page.locator('#formVincularGoogle button').isDisabled(), false);
    await page.unroute('**/api/auth/google/resultado');
    await page.route('**/api/auth/google/resultado', route => route.fulfill({ status: 400, json: { erro: 'Login com Google cancelado.' } }));
    await page.reload();
    await page.getByRole('heading', { name: 'Não foi possível entrar' }).waitFor();
    await page.route('**/api/auth/google/status', route => route.fulfill({ json: { disponivel: false } }));
    await page.goto(base + '/#/entrar');
    await page.getByText('Login com Google estará disponível em breve. Use e-mail e senha.').waitFor();
    assert.ok(await page.locator('#entrarGoogle').isDisabled());
    assert.deepEqual(erros, []);
    console.log(`Google UI: login, cadastro, vínculo, cancelamento e temas OK. Capturas: ${capturas}`);
  } finally { await browser.close(); }
};
